"""Unit 7 eval (SPEC §9): the same inputs through capture's workflow and agent modes, for the user
to judge side by side, with model calls, tool calls, krdict requests and seconds per run.

Calls the graph nodes directly: no capture rows, no cards. Needs the compose network (the agent
reaches the mcp service), so run it in a one-off container of the bot's image:
docker compose run --rm --no-deps -v <absolute repo path>/evals:/app/evals bot python -m evals.capture_ab
"""
import json
import sys
import time

from mbxchat import agent, capture, krdict
from evals.capture_side_by_side import PROMPTS
from evals.grader_eval import HERE

WORDS = [
    ("the word for optimization, a coworker said it", ""),
    ("word: deadline", ""),
    ("how do you say 'commute' as a noun", ""),
    ("Korean for receipt?", ""),
    ("procrastinate", ""),
]
COUNT = {"model": 0, "krdict": 0}


def _counting():
    ask, llm, fetch = capture.ask, agent._llm, krdict._fetch

    def counted_ask(*a, **k):
        COUNT["model"] += 1
        return ask(*a, **k)

    class CountedLLM:
        def __init__(self):
            self.inner = llm()

        def bind_tools(self, tools):
            self.inner = self.inner.bind_tools(tools)
            return self

        async def ainvoke(self, msgs):
            COUNT["model"] += 1
            return await self.inner.ainvoke(msgs)

    def counted_fetch(url):
        COUNT["krdict"] += 1
        return fetch(url)

    capture.ask, agent._llm, krdict._fetch = counted_ask, CountedLLM, counted_fetch
    agent.get_config = lambda: {"configurable": {"thread_id": "0"}}  # no capture row 0: the UPDATE is a no-op


def run(mode: str, text: str, situation: str) -> dict:
    COUNT.update(model=0, krdict=0)
    s = {"text": text, "situation": situation}
    t = time.perf_counter()
    try:
        if mode == "agent":
            s |= agent.agent(s)
            if s["kind"] == "word":
                s |= agent.word_lookup(s)
        else:
            s |= capture.draft(s)
        if s.get("kind") != "word":
            for node in (capture.lookup, capture.critic, capture.chunks):
                s |= node(s)
    except capture.CaptureError as e:
        s["error"] = str(e)
    return s | {"mode": mode, "seconds": round(time.perf_counter() - t, 1), "model_calls": COUNT["model"],
                "krdict_requests": COUNT["krdict"]}


def block(r: dict) -> list[str]:
    head = (f"### {r['mode']} ({r['seconds']} s, {r['model_calls']} model calls"
            + (f", {r.get('agent_calls', '?')} tool calls" if r["mode"] == "agent" else "") + f", {r['krdict_requests']} krdict)")
    if "error" in r:
        return [head, f"- failed: {r['error']}", ""]
    notes = [f"- ⚠️ {n}" for n in r.get("agent_notes", []) + r["findings"]["notes"]]
    if r.get("kind") == "word":
        w = r["word"]
        dic = agent.dictionary_line(w)
        return [head, f"- **word:** {w['korean']} · {w['english']}", f"- dictionary: {dic}",
                *[f"- example ({w['source']}): {e}" for e in w["examples"]], *notes, ""]
    rv = r["review"]
    return [head, f"- **casual:** {rv['casual']}", f"- **polite:** {rv['polite']}",
            *[f"- fix: {i}" for i in rv["issues"]],
            *[f"- chunk: {c['ko']} ({c['gloss']}, {c['kind']})" for c in r["chunks"]], *notes, ""]


def main() -> None:
    _counting()
    out = ["# Capture: workflow vs agent (generated by `evals/capture_ab.py`)", "",
           "Judge each pair: natural? right register? useful chunks or word card? Write your pick.", ""]
    log = []
    for text, situation in [*PROMPTS, *WORDS]:
        out += [f"## {text}" + (f" // {situation}" if situation else ""), ""]
        for mode in ("workflow", "agent"):
            r = run(mode, text, situation)
            if any(n.startswith("krdict unavailable") for n in r.get("findings", {}).get("notes", [])):
                sys.exit(f"stopped at the first krdict failure: {r['findings']['notes']}")
            log.append({k: r.get(k) for k in ("mode", "seconds", "model_calls", "agent_calls", "krdict_requests", "kind", "error")}
                       | {"text": text})
            out += block(r)
            print(mode, r["seconds"], r["model_calls"], text, flush=True)
        out += ["**pick:**", ""]
    (HERE / "results").mkdir(exist_ok=True)
    (HERE / "results" / "capture_ab.md").write_text("\n".join(out), encoding="utf-8")
    (HERE / "results" / "capture_ab.jsonl").write_text(
        "\n".join(json.dumps(x, ensure_ascii=False) for x in log) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
