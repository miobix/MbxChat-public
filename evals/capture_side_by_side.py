"""Capture side-by-side (SPEC §8, unit 6b): the same English prompts through draft → lookup → critic →
chunks on each model, into one Markdown file for the user to judge. Host only, needs MbxRead's API.

.venv/Scripts/python -m evals.capture_side_by_side MODEL [MODEL ...]
"""
import sys
import time

from mbxchat import capture, config
from evals.grader_eval import HERE

PROMPTS = [
    ("I'm running late, start without me", "to a friend"),
    ("Could you check the report before the meeting tomorrow?", "to my boss"),
    ("I've been meaning to call you, sorry it took so long", "to my aunt"),
    ("This is way too spicy for me", "at dinner with friends"),
    ("Is it okay if I pay by card?", "to a shop clerk"),
    ("I couldn't sleep at all because of the noise upstairs", "to a coworker"),
    ("Let's grab a coffee sometime next week", "to a new acquaintance"),
    ("The package was supposed to arrive yesterday", "to customer service"),
    ("I'm not sure I can make it, I'll let you know by tonight", "to a friend"),
    ("Thank you for taking care of me while I was sick", "to my mother-in-law"),
]


def run(model: str, text: str, situation: str) -> tuple[dict, float]:
    config.CAPTURE_MODEL = model
    state = {"text": text, "situation": situation}
    t = time.perf_counter()
    for node in (capture.draft, capture.lookup, capture.critic, capture.chunks):
        state |= node(state)
        if any(n.startswith("krdict") for n in state.get("findings", {}).get("notes", [])):
            sys.exit(f"stopped at the first krdict failure: {state['findings']['notes']}")
    return state, time.perf_counter() - t


def cell(state: dict) -> str:
    r = state["review"]
    lines = [f"- **casual:** {r['casual']}", f"- **polite:** {r['polite']}"]
    lines += [f"- fix: {i}" for i in r["issues"]]
    lines += [f"- chunk: {c['ko']} ({c['gloss']}, {c['kind']})" for c in state["chunks"]]
    return "\n".join(lines)


def main(models: list[str]) -> None:
    out = ["# Capture side-by-side (generated by `evals/capture_side_by_side.py`)", "",
           "Judge each block: natural? right register? useful chunks? Write your pick under each prompt.", ""]
    for text, situation in PROMPTS:
        out += [f"## {text} // {situation}", ""]
        for m in models:
            try:
                state, secs = run(m, text, situation)
                out += [f"### {m} ({secs:.0f} s)", cell(state), ""]
            except capture.CaptureError as e:
                out += [f"### {m}", f"- failed: {e}", ""]
            print(m, text, flush=True)
        out += ["**pick:**", ""]
    (HERE / "results").mkdir(exist_ok=True)
    (HERE / "results" / "capture_side_by_side.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1:])
